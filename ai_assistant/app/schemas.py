from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Request payload sent to the AI Assistant chat endpoint."""

    prompt: str = Field(
        ...,
        min_length=1,
        description="The user's question or message about Mimouna Bookstore.",
        examples=["ما هي الكتب المتوفرة في المتجر؟ وكم سعر التوصيل إلى ولاية بسكرة؟"],
    )


class ChatResponse(BaseModel):
    """Response returned by the AI Assistant chat endpoint."""

    success: bool = Field(default=True, description="Indicates whether the request succeeded.")
    response: str = Field(..., description="The textual answer generated by the AI agent.")


class HealthResponse(BaseModel):
    """Health check status payload."""

    status: str = "ok"
    model: str
    ollama_base_url: str
    bookstore_api_base_url: str
